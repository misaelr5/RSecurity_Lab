  await page.getByRole('button', { name: 'Importar archivo' }).click()
  await expect(page.getByText('3 nuevas', { exact: false })).toBeVisible()
  await page.getByRole('link', { name: 'Taller Cauce (ficticio)' }).click()
  await page.getByRole('button', { name: 'Crear borrador' }).click()
  await page.getByText('Aprobar mensaje', { exact: true }).click()
