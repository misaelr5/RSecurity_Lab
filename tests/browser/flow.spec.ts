import { test, expect } from '@playwright/test'
import { resolve } from 'node:path'

test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Clave local').fill('clave-sintetica-de-pruebas-e2e')
  await page.getByRole('button', { name: 'Iniciar sesión' }).click()
  await expect(page.getByRole('heading', { name: 'Dashboard' })).toBeVisible()
})

test('cartera desde CSV, aprobación manual, fixture e informe en Chrome', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Dashboard' })).toBeVisible()
  await page.getByRole('link', { name: 'Abrir cartera' }).click()
  await expect(page.getByText('No hay fichas para estos filtros.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Importar CSV o JSON', exact: true }).click()
  await page.getByLabel('Archivo de prospectos').setInputFiles(resolve('fixtures/prospectos-demo.csv'))
  await page.getByRole('button', { name: 'Importar archivo' }).click()
  await expect(page.getByText('3 nuevas', { exact: false })).toBeVisible()
  await page.getByRole('link', { name: 'Taller Cauce (ficticio)' }).click()
  await page.getByRole('button', { name: 'Crear borrador' }).click()
  await page.getByText('Aprobar mensaje', { exact: true }).click()
  await page.getByLabel('Responsable de la revisión').fill('Operador ficticio')
  await page.getByLabel('Confirmo que revisé el contenido.').check()
  await page.getByRole('button', { name: 'Aprobar para uso manual' }).click()
  await expect(page.getByText('Aprobado para uso manual · Operador ficticio')).toBeVisible()
  await page.getByRole('link', { name: 'Auditorías' }).click()
  await page.getByRole('button', { name: 'Ejecutar fixture local' }).click()
  await expect(page.getByText('Completada', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Ver informe' }).click()
  await expect(page.getByText('Borrador', { exact: true })).toBeVisible()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Descargar HTML' }).click()
  expect((await downloading).suggestedFilename()).toBe('reac-informe-v1.html')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('link', { name: 'Dashboard' }).click()
  await expect(page.getByRole('heading', { name: 'Cartera de prospectos' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  expect(errors).toEqual([])
})

test('importa y revisa evidencia defensiva documental', async ({ page }) => {
  await page.goto('/#audits')
  await page.getByRole('button', { name: 'Resultados defensivos' }).click()
  await page.getByLabel('Archivo de resultados').setInputFiles(resolve('fixtures/resultados-defensivos-demo.json'))
  await page.getByRole('button', { name: 'Importar resultados' }).click()
  await page.getByRole('link', { name: 'Revisar resultados' }).click()
  await expect(page.getByText('Pendiente de validación', { exact: true })).toBeVisible()
  await page.getByText('Revisar resultado', { exact: true }).click()
  await page.getByLabel('Nuevo estado').selectOption('Falso positivo')
  await page.getByLabel('Responsable de la revisión').fill('Operador QA')
  await page.getByLabel('Referencia a evidencia redactada').fill('Expediente QA')
  await page.getByRole('button', { name: 'Guardar revisión' }).click()
  await expect(page.getByText('Falso positivo', { exact: true }).first()).toBeVisible()
  await page.getByRole('link', { name: 'Ver informe' }).click()
  await expect(page.getByText(/Expediente QA/)).toBeVisible()
  await page.emulateMedia({ media: 'print' })
  await expect(page.getByText('Reac Studio · Documento confidencial')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Imprimir o guardar PDF' })).toBeHidden()
  const file = await page.pdf({ format: 'A4' })
  expect(file.subarray(0, 5).toString()).toBe('%PDF-')
})

test('descubrimiento, evidencia, prioridad, borrador y CRM desde la interfaz', async ({ page }) => {
  await page.getByRole('link', { name: 'Descubrimiento' }).click()
  await page.getByLabel('Archivo de investigación JSON').setInputFiles(resolve('fixtures/investigacion-demo.json'))
  await page.getByRole('button', { name: 'Previsualizar investigación' }).click()
  await expect(page.getByText(/sucursal ficticia/)).toBeVisible()
  await page.getByLabel('Responsable de la revisión').fill('Operador QA')
  await page.getByLabel('Verifiqué fuentes, canales públicos y atribución.').check()
  await page.getByRole('button', { name: 'Incorporar fichas verificadas' }).click()
  await page.getByRole('link', { name: 'Prospectos' }).click()
  await page.getByLabel('Tipo de aplicación').selectOption('Comercio electrónico')
  await page.getByRole('link', { name: 'Comercio Ficticio' }).click()
  await expect(page.getByRole('heading', { name: 'Prioridad comercial' })).toBeVisible()
  await page.getByRole('button', { name: 'Crear borrador', exact: true }).click()
  await expect(page.getByRole('paragraph').filter({ hasText: /En su sitio vi lo siguiente/ })).toBeVisible()
  await page.getByRole('link', { name: 'Descubrimiento' }).click()
  await page.getByRole('button', { name: 'Previsualizar para Reac Leads' }).click()
  await expect(page.getByText('Comercio → Otro · Sin borrador aprobado')).toBeVisible()
  const file = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Descargar CSV para Reac Leads' }).click()
  expect((await file).suggestedFilename()).toBe('reac-leads-v1.csv')
})
